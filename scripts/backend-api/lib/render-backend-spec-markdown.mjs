import { stringify } from 'yaml'
import { MD_NONE, renderBullets, renderTable } from './markdown-table.mjs'

/**
 * @param {Record<string, unknown>} spec
 * @param {{ specFile: string, slug: string }} context
 */
export function renderBackendSpecMarkdown(spec, context) {
  const feature = spec.feature ?? {}
  const title = feature.title ?? feature.id ?? context.slug
  const lines = [
    `# ${title}`,
    '',
    `- **Feature ID:** \`${feature.id ?? context.slug}\``,
    `- **Version:** \`${feature.version ?? '—'}\``,
    `- **Status:** \`${feature.status ?? '—'}\``,
    `- **Source YAML:** \`${context.specFile}\``,
    `- **Business Spec:** [📖 View Screen / Function Spec](../)`,
    renderApprovalLine(spec.approval),
    '',
    feature.source?.updatedAt ? `*Portal sync: ${feature.source.updatedAt}*` : '',
    ''
  ].filter(Boolean)

  if (feature.source) {
    lines.push('## Source', '', renderSource(feature.source), '')
  }

  if (spec.approval) {
    lines.push('## Approval', '', '```yaml', stringify(spec.approval).trim(), '```', '')
  }

  const endpoints = spec.api?.endpoints ?? []
  if (endpoints.length) {
    lines.push(
      '## Endpoints',
      '',
      renderTable(
        ['ID', 'Method', 'Path', 'Action', 'Purpose'],
        endpoints.map((e) => [e.id, e.method, e.path, e.action, e.purpose ?? ''])
      ),
      ''
    )
  }

  if (spec.requirements) {
    lines.push('## Requirements', '', '```yaml', stringify(spec.requirements).trim(), '```', '')
  }

  const debt = spec.pendingTechDebt ?? []
  if (debt.length) {
    lines.push(
      '## Pending tech debt',
      '',
      renderTable(
        ['ID', 'Status', 'Summary'],
        debt.map((d) => [d.id, d.status, d.summary ?? ''])
      ),
      ''
    )
  }

  const beOnly = spec.beOnlyRequirements ?? []
  if (beOnly.length) {
    lines.push('## BE-only requirements', '', renderBullets(beOnly), '')
  }

  if (spec.codegen) {
    lines.push('## Codegen', '', '```yaml', stringify(spec.codegen).trim(), '```', '')
  }

  if (spec.tags?.length) {
    lines.push('## Tags', '', renderBullets(spec.tags), '')
  }

  const changelog = spec.changeLog ?? []
  if (changelog.length) {
    lines.push(
      '## Change log',
      '',
      renderTable(
        ['ID', 'Source', 'Summary', 'Breaking'],
        changelog.map((c) => [c.id, c.source, c.summary, c.breaking ? 'yes' : 'no'])
      ),
      ''
    )
  }

  const decisions = spec.decisions ?? []
  if (decisions.length) {
    lines.push(
      '## Decisions',
      '',
      renderTable(
        ['ID', 'Summary'],
        decisions.map((d) => [d.id, d.summary ?? ''])
      ),
      ''
    )
  }

  const openQuestions = spec.openQuestions ?? []
  if (openQuestions.length) {
    lines.push(
      '## Open questions',
      '',
      renderTable(
        ['ID', 'Question', 'Tag'],
        openQuestions.map((q) => [q.id, q.question ?? '', q.tag ?? ''])
      ),
      ''
    )
  }

  lines.push(
    '## Related files',
    '',
    '- [02-openapi.yaml](../02-openapi.yaml)',
    '- [03-mock-data.yaml](../03-mock-data.yaml)',
    '',
    '---',
    '',
    '*Generated by `pnpm docs:render` — do not edit by hand.*',
    ''
  )

  return lines.join('\n')
}

/**
 * @param {Record<string, unknown>} spec — common fragment (no feature block)
 */
export function renderCommonSpecMarkdown(spec, context) {
  const title = spec.title ?? spec.id ?? context.slug
  const lines = [
    `# ${title}`,
    '',
    spec.summary ? `${spec.summary}\n` : '',
    `- **Source YAML:** \`${context.specFile}\``,
    ''
  ]

  for (const [key, value] of Object.entries(spec)) {
    if (['id', 'title', 'summary'].includes(key) || value == null) continue
    lines.push(`## ${key}`, '', '```yaml', stringify(value).trim(), '```', '')
  }

  lines.push('---', '', '*Generated by `pnpm docs:render` — do not edit by hand.*', '')
  return lines.join('\n')
}

function renderApprovalLine(approval) {
  if (!approval) return `- **Approval:** ${MD_NONE}`
  return `- **Approval:** \`${approval.status ?? '—'}\`${approval.reviewedBy ? ` (${approval.reviewedBy})` : ''}`
}

function renderSource(source) {
  const rows = []
  if (source.portalSpec) rows.push(`- Portal spec: \`${source.portalSpec}\``)
  if (source.portalTestcases) rows.push(`- Portal testcases: \`${source.portalTestcases}\``)
  for (const ref of source.portalRefs ?? []) {
    rows.push(`- Portal ref **${ref.id}**: \`${ref.status}\`${ref.syncedAt ? ` (synced ${ref.syncedAt})` : ''}`)
  }
  return rows.length ? rows.join('\n') : MD_NONE
}
